<?php

declare(strict_types=1);

/**
 * Template Name: Login
 * Template Post Type: page
 */

use HKS\Auth\Auth;

$auth = new Auth();

/*
|--------------------------------------------------------------------------
| ログイン済みならマイページへ
|--------------------------------------------------------------------------
*/

if ($auth->check()) {
    wp_safe_redirect(home_url('/mypage/'));
    exit;
}

/*
|--------------------------------------------------------------------------
| 初期値
|--------------------------------------------------------------------------
*/

$error = '';

/*
|--------------------------------------------------------------------------
| ログイン処理
|--------------------------------------------------------------------------
*/

if ($_SERVER['REQUEST_METHOD'] === 'POST') {

    $result = $auth->login($_POST);

    if (($result['success'] ?? false) === true) {

        wp_safe_redirect(home_url('/mypage/'));
        exit;
    }

    $error = (string) ($result['message'] ?? 'ログインに失敗しました。');
}

/*
|--------------------------------------------------------------------------
| View
|--------------------------------------------------------------------------
*/

get_header();

require get_template_directory() . '/views/auth/login.php';

get_footer();