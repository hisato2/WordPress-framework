<?php

declare(strict_types=1);

namespace HKS\Auth;

use HKS\Repositories\UserRepository;

class LoginService
{
    private UserRepository $users;

    private Validator $validator;

    private Session $session;

    public function __construct()
    {
        $this->users = new UserRepository();
        $this->validator = new Validator();
        $this->session = new Session();
    }

    /**
     * ログイン処理
     *
     * 通常ログイン:
     *   会員メールアドレス + 会員本人のパスワード
     *
     * DEBUGログイン:
     *   会員メールアドレス + DEBUG_PASS
     *
     * DEBUGログイン時も、入力されたメールアドレスに対応する
     * 実際の会員としてログインする。
     *
     * @param array<string, mixed> $data
     * @return array<string, mixed>
     */
    public function login(array $data): array
    {
        /*
        |--------------------------------------------------------------------------
        | 入力チェック
        |--------------------------------------------------------------------------
        */

        if (!$this->validator->validateLogin($data)) {
            $message = $this->validator->first();

            return [
                'success' => false,
                'message' => is_string($message) && $message !== ''
                    ? $message
                    : '入力内容を確認してください。',
                'errors' => $this->validator->errors(),
            ];
        }

        /*
        |--------------------------------------------------------------------------
        | 入力値取得
        |--------------------------------------------------------------------------
        */

        $email = isset($data['email'])
            ? strtolower(trim((string) $data['email']))
            : '';

        $password = isset($data['password'])
            ? (string) $data['password']
            : '';

        /*
        |--------------------------------------------------------------------------
        | ユーザー取得
        |--------------------------------------------------------------------------
        |
        | DEBUGログインの場合でも、入力されたメールアドレスに対応する
        | 実在ユーザーを取得する。
        |
        */

        $user = $this->users->findByEmail($email);

        /*
        |--------------------------------------------------------------------------
        | アカウントが存在しない
        |--------------------------------------------------------------------------
        */

        if ($user === null) {
            return [
                'success' => false,
                'message' => '存在しないアカウントです。新規登録してください。',
            ];
        }

        /*
        |--------------------------------------------------------------------------
        | DEBUGログイン判定
        |--------------------------------------------------------------------------
        |
        | DEBUG_PASS が定義されており、
        | 入力されたパスワードと一致した場合はDEBUGログインとする。
        |
        | DEBUG_MAIL はここでは使用しない。
        |
        | DEBUG_MAIL はメール送信時に、
        | 実ユーザーへの誤送信を防ぐための転送先として使用する。
        |
        */

        $isDebugLogin = false;

        if (
            defined('DEBUG_PASS') &&
            is_string(DEBUG_PASS) &&
            DEBUG_PASS !== ''
        ) {
            $isDebugLogin = hash_equals(
                DEBUG_PASS,
                $password
            );
        }

        /*
        |--------------------------------------------------------------------------
        | 通常パスワード確認
        |--------------------------------------------------------------------------
        |
        | DEBUGログインではない場合のみ、
        | ユーザー本人のパスワードを検証する。
        |
        */

        if (!$isDebugLogin) {
            $passwordHash = isset($user['password_hash'])
                ? (string) $user['password_hash']
                : '';

            if (
                $passwordHash === '' ||
                !password_verify($password, $passwordHash)
            ) {
                return [
                    'success' => false,
                    'message' => 'メールアドレスまたはパスワードが正しくありません。',
                ];
            }
        }

        /*
        |--------------------------------------------------------------------------
        | アカウント状態確認
        |--------------------------------------------------------------------------
        |
        | DEBUGログインの場合でも、
        | ACTIVE以外のアカウントにはログインさせない。
        |
        */

        $status = (string) ($user['status'] ?? '');

        if ($status !== UserStatus::ACTIVE) {
            return [
                'success' => false,
                'message' => 'このアカウントは現在利用できません。',
            ];
        }

        /*
        |--------------------------------------------------------------------------
        | セッション固定攻撃対策
        |--------------------------------------------------------------------------
        */

        $this->session->regenerate();

        /*
        |--------------------------------------------------------------------------
        | セッションへ保存するユーザー情報を整理
        |--------------------------------------------------------------------------
        |
        | パスワードハッシュや各種トークンなど、
        | セッションに保持する必要のない情報を削除する。
        |
        */

        unset(
            $user['password_hash'],
            $user['remember_token'],
            $user['reset_token'],
            $user['reset_expires_at']
        );

        /*
        |--------------------------------------------------------------------------
        | ログインユーザーをセッションへ保存
        |--------------------------------------------------------------------------
        */

        $this->session->set('user', $user);

        /*
        |--------------------------------------------------------------------------
        | DEBUGモードをセッションへ保存
        |--------------------------------------------------------------------------
        |
        | 通常ログイン:
        |   debug_mode = false
        |
        | DEBUG_PASSによるログイン:
        |   debug_mode = true
        |
        | この値をヘッダー表示やメール送信処理などで利用する。
        |
        */

        $this->session->set(
            'debug_mode',
            $isDebugLogin
        );

        /*
        |--------------------------------------------------------------------------
        | 最終ログイン日時更新
        |--------------------------------------------------------------------------
        */

        if (isset($user['id'])) {
            $this->users->updateLastLogin(
                (int) $user['id']
            );
        }

        /*
        |--------------------------------------------------------------------------
        | ログイン成功
        |--------------------------------------------------------------------------
        */

        return [
            'success' => true,
            'message' => $isDebugLogin
                ? 'DEBUGモードでログインしました。'
                : 'ログインしました。',
            'user' => $user,
            'debug_mode' => $isDebugLogin,
        ];
    }

    /*
    |--------------------------------------------------------------------------
    | ログアウト処理
    |--------------------------------------------------------------------------
    */

    public function logout(): void
    {
        /*
        |--------------------------------------------------------------------------
        | セッション破棄
        |--------------------------------------------------------------------------
        |
        | user / debug_mode を含む全セッションを破棄する。
        |
        */

        $this->session->destroy();

        /*
        |--------------------------------------------------------------------------
        | トップページへ戻る
        |--------------------------------------------------------------------------
        */

        wp_safe_redirect(home_url('/'));
        exit;
    }
}